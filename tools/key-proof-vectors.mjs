#!/usr/bin/env node
/** Test vectors for the `key` proof (protocol/challenge.js) and the canonical JSON it signs, for verifiers outside
 *  this repo. RO3Emu's server checks the arcade's account-link proof in C#, and these are its byte-for-byte reference.
 *  ed25519 is deterministic, so the same seeds always give the same file:
 *    node tools/key-proof-vectors.mjs          write demo/fixtures/key-proof-vectors.json
 *    node tools/key-proof-vectors.mjs --check  exit 1 when the file is stale */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { canonical, sha256Hex } from '../protocol/canonical.js';
import { KEY_TAG, keyProofBody, signKeyProof } from '../protocol/challenge.js';
import { signingBytes, toHex } from '../protocol/keys.js';

const file = join(dirname(fileURLToPath(import.meta.url)), '..', 'demo', 'fixtures', 'key-proof-vectors.json');

// Public key of a seed, from WebCrypto (the seed is the PKCS#8 private key's last 32 bytes, as protocol/keys.js keeps it).
async function publicOf(seedHex) {
  const pkcs8 = Buffer.concat([Buffer.from('302e020100300506032b657004220420', 'hex'), Buffer.from(seedHex, 'hex')]);
  const key = await crypto.subtle.importKey('pkcs8', pkcs8, { name: 'Ed25519' }, true, ['sign']);
  const jwk = await crypto.subtle.exportKey('jwk', key);
  return Buffer.from(jwk.x, 'base64url').toString('hex');
}

export async function vectors() {
  const seeds = [sha256Hex('key-proof-vector-0'), sha256Hex('key-proof-vector-1')];
  const claims = [
    { aud: 'ro3.realm-a', nonce: '00112233445566778899aabbccddeeff', rulesetId: 'ro3.v1' },
    { aud: 'ro3-link', nonce: 'f'.repeat(64), rulesetId: 'ro3.v1' },
    { aud: 'pb-matchmaker', nonce: '0123456789abcdef', rulesetId: 'pickle-brawl.v1' },
  ];
  const proofs = [];
  for (const [i, seed] of seeds.entries()) {
    const player = await publicOf(seed);
    for (const c of claims) {
      const claim = { ...c, player };
      const body = keyProofBody(claim);
      proofs.push({ seed, player, claim, canonical: canonical(body), signingBytes: toHex(signingBytes(KEY_TAG, body)), sig: await signKeyProof(claim, seed), valid: true });
    }
    if (i === 0) {
      // Each must fail: a field changed after signing, or another key named as the signer.
      const claim = { ...claims[0], player };
      const sig = await signKeyProof(claim, seed);
      proofs.push({ seed, player, claim: { ...claim, aud: 'ro3.realm-b' }, sig, valid: false, why: 'aud changed' });
      proofs.push({ seed, player, claim: { ...claim, nonce: claim.nonce.replace(/^0/, '1') }, sig, valid: false, why: 'nonce changed' });
      proofs.push({ seed, player: await publicOf(seeds[1]), claim: { ...claim, player: await publicOf(seeds[1]) }, sig, valid: false, why: 'another key' });
      proofs.push({ seed, player, claim, sig: sig.slice(0, -2) + (sig.endsWith('00') ? '01' : '00'), valid: false, why: 'signature altered' });
    }
  }
  // canonical(): keys sorted at every depth, undefined dropped, arrays kept in order, strings escaped as JSON.stringify does.
  const canon = [
    { value: { b: 1, a: { d: [3, 1], c: 'x' } }, canonical: canonical({ b: 1, a: { d: [3, 1], c: 'x' } }) },
    { value: { z: 'é"\\\n\u0001', y: null, x: true, w: -1.5 }, canonical: canonical({ z: 'é"\\\n\u0001', y: null, x: true, w: -1.5 }) },
  ];
  return { tag: KEY_TAG, note: 'Generated by tools/key-proof-vectors.mjs. Signed bytes: tag NUL canonical(body); body = { aud, nonce, player, rulesetId }.', proofs, canonical: canon };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const text = JSON.stringify(await vectors(), null, 2) + '\n';
  if (process.argv.includes('--check')) {
    const was = (() => { try { return readFileSync(file, 'utf8'); } catch { return ''; } })();
    if (was !== text) { console.error(`${file} is stale: node tools/key-proof-vectors.mjs`); process.exit(1); }
    console.log('key-proof vectors up to date');
  } else { writeFileSync(file, text); console.log(`wrote ${file}`); }
}
